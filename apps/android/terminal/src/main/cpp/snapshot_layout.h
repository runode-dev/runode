#define SNAPSHOT_IMAGE_SOURCE_HEIGHT 48
#define SNAPSHOT_IMAGE_GENERATION 56
#define SNAPSHOT_IMAGE_SIZE 64

#define SNAPSHOT_LAYER_BELOW_BACKGROUND 0
